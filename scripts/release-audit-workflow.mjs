#!/usr/bin/env node
// release-audit-workflow — build the runnable workflow script for /release-audit.
//
// WHY THIS EXISTS. The Workflow tool takes its input either as `args`, which must
// be written inline into the tool call, or as a script file. The collected
// document is tens of kilobytes even after projection, so the `args` route means
// transcribing that JSON by hand on every run — expensive, and a silent-corruption
// risk if a single character is mistyped. Emitting a self-contained script
// sidesteps both: the document is embedded from disk, byte-exact, and the tool is
// handed a path.
//
// The skill's canonical script lives in a markdown fence
// (maintainer-skills/release-audit/references/workflow-script.md) so that it is
// reviewable prose-adjacent and is not mistaken for a module `npm test` should
// execute. This reads that fence, injects the document, and writes the result.
//
// Usage:
//   node scripts/release-audit-workflow.mjs --input <wargs.json> --out <workflow.mjs>
//   node scripts/release-audit-workflow.mjs --input <wargs.json> --out <prompts.json> --prompts
//
// `--prompts` is for harnesses with no Workflow tool (Codex, agy): instead of a
// script it writes the work list — one prompt per unit, the report/verdict JSON
// schemas, and the refute-prompt template — so the harness can run each unit as a
// headless call (`codex exec --output-schema`, `agy -p --json-schema`) or a subagent.

import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));

export const WORKFLOW_MD = 'maintainer-skills/release-audit/references/workflow-script.md';

export function parseArgs(argv) {
  const out = { input: null, out: null, prompts: false };
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--prompts') { out.prompts = true; continue; }
    if (argv[i] === '--input') { out.input = argv[i + 1] ?? null; i += 1; continue; }
    if (argv[i] === '--out') { out.out = argv[i + 1] ?? null; i += 1; }
  }
  return out;
}

/**
 * The single ```javascript fence in the skill's workflow reference. Exactly one
 * is required: two would make "which block runs" a guess, and the wrong guess
 * produces a workflow that looks plausible and audits nothing.
 */
export function extractScript(markdown) {
  const blocks = [...String(markdown).matchAll(/```javascript\n([\s\S]*?)\n```/g)].map((m) => m[1]);
  if (blocks.length !== 1) {
    throw new Error(`expected exactly one javascript block in ${WORKFLOW_MD}, found ${blocks.length}`);
  }
  return blocks[0];
}

/** The line the built document replaces. Must follow `meta` in the template. */
export const INPUT_MARKER = '// <<INPUT_DOC>>';

/**
 * Inject the collected document into the script as `INPUT_DOC`.
 *
 * Injected AT A MARKER rather than prepended, because the Workflow runtime
 * requires `export const meta` to be the script's FIRST statement and rejects
 * anything placed ahead of it. The marker sits immediately after meta, so
 * INPUT_DOC is declared before the line that reads it.
 *
 * JSON.stringify output is a JavaScript expression for every value JSON.parse
 * can produce, with one exception that matters here: `</script` and
 * U+2028/U+2029 are legal in JSON strings and hostile in a script context. Issue
 * titles are written by anyone who can open an issue and land here verbatim, so
 * they are escaped rather than trusted.
 */
export function buildScript(doc, script) {
  const json = JSON.stringify(doc)
    .replace(/</g, '\\u003c')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
  if (!script.includes(INPUT_MARKER)) {
    throw new Error(`workflow template is missing its ${INPUT_MARKER} marker — the document has nowhere to go`);
  }
  const withDoc = script.replace(INPUT_MARKER, `const INPUT_DOC = ${json}`);
  return `${withDoc}\n\n// Generated by scripts/release-audit-workflow.mjs from ${WORKFLOW_MD} — do not edit.\n`;
}

/**
 * Run the built script once in prompts mode and return the work list it hands
 * to the PROMPTS_ONLY sink. Synchronous on purpose: the script reaches the sink
 * before its first await, so no promise needs settling. Nothing is spawned —
 * agent/pipeline/parallel throw if the script ever tries.
 */
export function extractPrompts(built) {
  const body = built.replace('export const meta', 'const meta');
  // The try/catch lives INSIDE the async wrapper so a runtime failure in the
  // script is reported through a synchronous sink with its real message, rather
  // than as a rejected promise this synchronous function cannot see.
  const fn = new vm.Script(`(async function (args, log, agent, pipeline, parallel, PROMPTS_ONLY, __fail) {\ntry {\n${body}\n} catch (e) { __fail(e) }\n})`)
    .runInNewContext({}, { timeout: 5000 });
  const refuse = () => { throw new Error('--prompts mode must not spawn agents'); };
  let captured = null;
  let failure = null;
  fn(undefined, () => {}, refuse, refuse, refuse, (prompts) => { captured = prompts; }, (e) => { failure = e; });
  if (failure) {
    throw new Error(`workflow script failed before reaching its PROMPTS_ONLY hook: ${failure?.message ?? failure}`, { cause: failure });
  }
  if (captured === null) throw new Error('workflow script never reached its PROMPTS_ONLY hook');
  return JSON.parse(JSON.stringify(captured)); // normalise vm-realm objects
}

export function workflowMain(argv = process.argv.slice(2), { readFile = readFileSync, writeFile = writeFileSync, log = console.log, root = ROOT } = {}) {
  const args = parseArgs(argv);
  if (!args.input || !args.out) {
    log('usage: release-audit-workflow --input <wargs.json> --out <workflow.mjs|prompts.json> [--prompts]');
    return 1;
  }
  const doc = JSON.parse(readFile(args.input, 'utf8'));
  const script = extractScript(readFile(join(root, WORKFLOW_MD), 'utf8'));
  const built = buildScript(doc, script);
  if (args.prompts) {
    const prompts = extractPrompts(built);
    writeFile(args.out, `${JSON.stringify(prompts, null, 2)}\n`);
    log(`wrote ${args.out} (${prompts.work.length} prompts, schemas and refute template)`);
    return 0;
  }
  writeFile(args.out, built);
  log(`wrote ${args.out} (${built.length} bytes, ${doc.units?.length ?? 0} units)`);
  return 0;
}

const invokedDirectly = process.argv[1]
  && realpathSync(fileURLToPath(import.meta.url)) === realpathSync(process.argv[1]);
if (invokedDirectly) process.exit(workflowMain());
