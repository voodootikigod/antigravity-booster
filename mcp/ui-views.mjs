function buildHtmlDocument({ title, appName, bodyHtml, viewJs }) {
  return [
    '<!DOCTYPE html>',
    '<html lang="en">',
    '<head>',
    '  <meta charset="utf-8">',
    '  <meta name="viewport" content="width=device-width, initial-scale=1">',
    `  <title>${title}</title>`,
    '  <style>',
    SHARED_CSS,
    '  </style>',
    '</head>',
    '<body>',
    bodyHtml,
    '  <script>',
    SHARED_RUNTIME_JS,
    viewJs,
    `__bridge.boot(${JSON.stringify(appName)});`,
    '  </script>',
    '</body>',
    '</html>',
  ].join('\n');
}

