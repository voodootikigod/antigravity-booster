test('preAnalyzeSpec: catches parallel scope overlaps, missing rails, and missing acceptance criteria in <50ms', () => {
  const brokenMd = `# Broken Spec

## 1. Overview
Broken test spec.

### Ticket 1: \`T-1\` — First
- **Scope**: \`src/shared/**\`
- **Rails**: \`nonexistent/rail.mjs\`
- **Objectives**:
  - Do work without acceptance criteria.

### Ticket 2: \`T-2\` — Second
- **Scope**: \`src/shared/sub.mjs\`
- **Acceptance Criteria**:
  - Works.
`;

  const t0 = performance.now();
  const res = preAnalyzeSpec(brokenMd, { repo: REPO_ROOT });
  const elapsed = performance.now() - t0;

  assert.ok(elapsed < 50, `Expected <50ms, took ${elapsed.toFixed(2)}ms`);
  assert.equal(res.structured, true);
  assert.equal(res.ok, false);
  assert.ok(res.structuralErrors.some((e) => e.includes('T-1: missing Acceptance Criteria')));
  assert.ok(res.structuralErrors.some((e) => e.includes('run in parallel but declare overlapping scopes')));
  assert.ok(res.structuralErrors.some((e) => e.includes("declared rail 'nonexistent/rail.mjs' does not exist")));
});

test('scanStaticImportCoupling: flags direct relative imports between concurrent tickets and ignores serialized tickets', () => {
  const tmpRepo = mkdtempSync(join(tmpdir(), 'agb-shape-coupling-'));
  try {
    mkdirSync(join(tmpRepo, 'src/a'), { recursive: true });
    mkdirSync(join(tmpRepo, 'src/b'), { recursive: true });
    writeFileSync(join(tmpRepo, 'src/a/consumer.mjs'), "import { helper } from '../b/provider.mjs';\nexport const x = helper();\n");
    writeFileSync(join(tmpRepo, 'src/b/provider.mjs'), 'export function helper() { return 42; }\n');

    const concurrentTickets = [
      { id: 'T1', scope: ['src/a/**'], edges: [] },
      { id: 'T2', scope: ['src/b/**'], edges: [] },
    ];
    const warnings = scanStaticImportCoupling(concurrentTickets, tmpRepo);
    assert.equal(warnings.length, 1);
    assert.equal(warnings[0].fromTicket, 'T1');
    assert.equal(warnings[0].toTicket, 'T2');
    assert.equal(warnings[0].importerFile, 'src/a/consumer.mjs');
    assert.equal(warnings[0].importedFile, 'src/b/provider.mjs');

    const serializedTickets = [
      { id: 'T1', scope: ['src/a/**'], edges: [] },
      { id: 'T2', scope: ['src/b/**'], edges: [{ to: 'T1' }] },
    ];
    assert.deepEqual(scanStaticImportCoupling(serializedTickets, tmpRepo), []);
  } finally {
    rmSync(tmpRepo, { recursive: true, force: true });
  }
});

test('syncBrainPlanArtifact & formatShapeReport: atomically writes brain artifact and .booster/agb_plan_artifact.md and rejects traversal', () => {
  const brainDir = mkdtempSync(join(tmpdir(), 'agb-shape-brain-'));
  const tmpRepo = mkdtempSync(join(tmpdir(), 'agb-shape-repo-'));
  try {
    const bad = syncBrainPlanArtifact('# Plan', { repo: '', brainDir, sessionId: '../escape' });
    assert.equal(bad.ok, false);
    const badDot = syncBrainPlanArtifact('# Plan', { repo: '', brainDir, sessionId: '.' });
    assert.equal(badDot.ok, false);

    const good = syncBrainPlanArtifact('# Hardened Plan\n', { repo: tmpRepo, brainDir, sessionId: 'conv-123' });
    assert.equal(good.ok, true);
    assert.equal(readFileSync(good.path, 'utf8'), '# Hardened Plan\n');
    assert.equal(readFileSync(join(tmpRepo, '.booster', 'agb_plan_artifact.md'), 'utf8'), '# Hardened Plan\n');

    const reportText = formatShapeReport({
      ok: true,
      structured: true,
      plan: { tickets: [{ id: 'T1' }] },
      structuralErrors: [],
      couplingWarnings: [],
      scopeWarnings: [],
      readinessScore: 100,
    });
    assert.match(reportText, /agb shape: PASS/);
  } finally {
    rmSync(brainDir, { recursive: true, force: true });
    rmSync(tmpRepo, { recursive: true, force: true });
  }
});

test('safeExtractJson & validateJsonSchema: repairs malformed LLM JSON, preserves inner fences, and skips leading prose brackets', () => {
  const raw = 'Here is the JSON:\n```json\n{"gaps": ["missing a\\s+b",],}\n```';
  const parsed = safeExtractJson(raw);
  assert.deepEqual(parsed, { gaps: ['missing a\\s+b'] });
  const v = validateJsonSchema(parsed, COLDSTART_SCHEMA);
  assert.equal(v.valid, true);

  const innerFence = '```json\n{"body": "Diagram:\\n```mermaid\\ngraph TD\\n  A-->B\\n```"}\n```';
  const parsedInner = safeExtractJson(innerFence);
  assert.match(parsedInner.body, /```mermaid/);

  const leadingNote = 'Note [1]: see the object below:\n{"gaps": ["item"]}';
  assert.deepEqual(safeExtractJson(leadingNote), { gaps: ['item'] });
});

test('parseStructuredSpec { gate } option, non-DAG sequenceDiagram ignore, and AGB_GRAPH_COUPLING_FILE support', () => {
  const md = [
    '# Sequence Spec',
    '```mermaid',
    'sequenceDiagram',
    '  T-1->>T-2: message not a dependency edge',
    '```',
    '### Ticket 1: `T-1` — First',
    '- **Scope**: `src/a.mjs`',
    '- **Acceptance Criteria**:',
    '  - Works.',
    '### Ticket 2: `T-2` — Second',
    '- **Scope**: `src/b.mjs`',
    '- **Acceptance Criteria**:',
    '  - Works.',
  ].join('\n');
  const parsed = parseStructuredSpec(md, { repo: REPO_ROOT, gate: { test: 'pytest' } });
  assert.equal(parsed.structured, true);
  assert.deepEqual(parsed.plan.gate, { test: 'pytest' });
  assert.deepEqual(parsed.plan.tickets[0].edges, []);
  assert.deepEqual(parsed.plan.tickets[1].edges, []);

  const tmpRepo = mkdtempSync(join(tmpdir(), 'agb-coupling-file-'));
  const prevEnv = process.env.AGB_GRAPH_COUPLING_FILE;
  try {
    const couplingFile = join(tmpRepo, 'custom-coupling.json');
    writeFileSync(couplingFile, JSON.stringify({ 'src/a.mjs': ['src/b.mjs'] }));
    process.env.AGB_GRAPH_COUPLING_FILE = couplingFile;
    const warnings = scanStaticImportCoupling(parsed.plan.tickets, tmpRepo);
    assert.equal(warnings.length, 1);
    assert.equal(warnings[0].fromTicket, 'T-1');
    assert.equal(warnings[0].toTicket, 'T-2');
  } finally {
    if (prevEnv === undefined) delete process.env.AGB_GRAPH_COUPLING_FILE;
    else process.env.AGB_GRAPH_COUPLING_FILE = prevEnv;
    rmSync(tmpRepo, { recursive: true, force: true });
  }
});
